/* ============================================================
   MODAL INTERACTION SYSTEM
   ============================================================ */

(function () {
  const modal = document.getElementById('pillar-modal');
  const overlay = document.getElementById('modal-overlay');
  const modalClose = document.getElementById('modal-close');
  const modalBadge = document.getElementById('modal-badge');
  const modalTitle = document.getElementById('modal-title');
  const modalBody = document.getElementById('modal-body');

  if (!modal) return;

  function openModal(id) {
    const data = window.PILLAR_DATA[id];
    if (!data) return;

    modalBadge.textContent = data.badge;
    modalTitle.textContent = data.title;
    modalBody.innerHTML = data.body;

    modal.classList.add('open');
    overlay.classList.add('open');
    document.body.style.overflow = 'hidden';

    const inner = modal.querySelector('.modal__inner');
    if (inner) inner.scrollTop = 0;

    setTimeout(() => modalClose && modalClose.focus(), 80);
  }

  function closeModal() {
    modal.classList.remove('open');
    overlay.classList.remove('open');
    document.body.style.overflow = '';
  }

  document.addEventListener('click', function (e) {
    const trigger = e.target.closest('[data-pillar]');
    if (trigger) {
      const id = parseInt(trigger.dataset.pillar, 10);
      openModal(id);
    }
  });

  if (overlay) overlay.addEventListener('click', closeModal);
  if (modalClose) modalClose.addEventListener('click', closeModal);

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && modal.classList.contains('open')) {
      closeModal();
    }
  });

  document.querySelectorAll('[data-pillar][role="button"]').forEach(function (el) {
    el.addEventListener('keydown', function (e) {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        openModal(parseInt(el.dataset.pillar, 10));
      }
    });
  });
}());
